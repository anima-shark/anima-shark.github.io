const i18n = (() => {
  function saved() {
    try { return localStorage.getItem('lang'); } catch { return null; }
  }

  function initialLang() {
    const fromUrl = new URLSearchParams(location.search).get('lang');
    const browser = (navigator.language || '').toLowerCase().slice(0, 2);
    const pick = fromUrl || saved() || (I18N[browser] && browser !== 'uk' ? browser : 'uk');
    return I18N[pick] ? pick : 'uk';
  }

  let lang = initialLang();
  const t = (key) => I18N[lang][key] ?? I18N.uk[key] ?? key;

  function apply() {
    document.documentElement.lang = lang;
    document.title = t('meta.title');
    document.querySelector('meta[name="description"]').content = t('meta.desc');
    document.querySelector('meta[property="og:title"]').content = t('meta.title');
    document.querySelector('meta[property="og:description"]').content = t('meta.desc');

    document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
    document.querySelectorAll('[data-i18n-aria]').forEach((el) => el.setAttribute('aria-label', t(el.dataset.i18nAria)));
    document.querySelectorAll('[data-wa]').forEach((el) => {
      el.href = `https://wa.me/${el.dataset.wa}?text=${encodeURIComponent(t('wa.msg'))}`;
    });
    document.querySelectorAll('[data-i18n-alt]').forEach((el) => el.setAttribute('alt', t(el.dataset.i18nAlt)));

    const group = document.getElementById('langSwitch');
    if (group) {
      group.setAttribute('aria-label', t('lang.aria'));
      group.querySelectorAll('button').forEach((b) => b.setAttribute('aria-pressed', String(b.dataset.lang === lang)));
    }
    document.dispatchEvent(new Event('langchange'));
  }

  function set(next) {
    lang = next;
    try { localStorage.setItem('lang', lang); } catch {}
    apply();
  }

  return { t, apply, set };
})();
